<script>
function openOverlay(name) { document.getElementById('ov-' + name).classList.add('open'); }
function closeOverlay(name) { document.getElementById('ov-' + name).classList.remove('open'); }

(function () {
    var box = document.getElementById('countdown');
    if (!box) return;
    var endsAt = parseInt(box.dataset.endsAt, 10);
    var endedText = @json($t['ended']);
    var cells = {
        d: document.getElementById('cd-d'),
        h: document.getElementById('cd-h'),
        m: document.getElementById('cd-m'),
        s: document.getElementById('cd-s')
    };
    function pad(n) { return n < 10 ? '0' + n : '' + n; }
    function tick() {
        var diff = endsAt - Date.now();
        if (diff <= 0) {
            box.innerHTML = '<span class="cd-label">' + endedText + '</span>';
            clearInterval(timer);
            return;
        }
        var secs = Math.floor(diff / 1000);
        cells.d.textContent = pad(Math.floor(secs / 86400));
        cells.h.textContent = pad(Math.floor((secs % 86400) / 3600));
        cells.m.textContent = pad(Math.floor((secs % 3600) / 60));
        cells.s.textContent = pad(secs % 60);
    }
    tick();
    var timer = setInterval(tick, 1000);
})();
</script>
