<script>
var myRanks = @json($my['ranks'] ?? []);
var notRanked = @json($t['not_ranked']);
var endedText = @json($t['ended']);

function switchTab(key) {
    document.querySelectorAll('.tab').forEach(function (b) { b.classList.toggle('active', b.dataset.tab === key); });
    document.querySelectorAll('.panel').forEach(function (p) { p.classList.toggle('active', p.id === 'panel-' + key); });
    var rankEl = document.getElementById('my-rank');
    if (rankEl) rankEl.textContent = myRanks[key] || notRanked;
}
function openRules() { document.getElementById('ov-rules').classList.add('open'); }
function closeRules() { document.getElementById('ov-rules').classList.remove('open'); }

(function () {
    var box = document.getElementById('countdown');
    if (!box) return;
    var ends = parseInt(box.dataset.ends, 10) * 1000;
    var d = document.getElementById('cd-d'),
        h = document.getElementById('cd-h'),
        m = document.getElementById('cd-m'),
        s = document.getElementById('cd-s');
    function pad(n) { return n < 10 ? '0' + n : '' + n; }
    function tick() {
        var left = ends - Date.now();
        if (left <= 0) {
            box.innerHTML = '<span class="lbl">' + endedText + '</span>';
            clearInterval(timer);
            return;
        }
        var sec = Math.floor(left / 1000);
        d.textContent = Math.floor(sec / 86400);
        h.textContent = pad(Math.floor((sec % 86400) / 3600));
        m.textContent = pad(Math.floor((sec % 3600) / 60));
        s.textContent = pad(sec % 60);
    }
    tick();
    var timer = setInterval(tick, 1000);
})();
</script>
